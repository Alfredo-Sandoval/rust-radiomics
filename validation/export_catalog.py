"""Regenerate the Rust feature catalogue from an installed mlx-radiomics.

The catalogue is part of the public contract: names, order, family membership and the
93-name default selection must match mlx-radiomics exactly. Run it with the Python
environment that has ``mlxradiomics`` installed, for example::

    ../mlx-radiomics/.venv/bin/python -I validation/export_catalog.py \
        --ibsi ../mlx-radiomics/docs/ibsi-features.json \
        --rust crates/radiomics/src/config/settings/catalog.rs \
        --markdown validation/catalog.md
    cargo +1.96.0 fmt

``--ibsi`` is mlx-radiomics' IBSI manifest (identifiers and titles from the IBSI
reference manual, CC BY 4.0). ``--markdown`` writes per-family review tables.
"""

import argparse
import json
import subprocess
from pathlib import Path

import mlxradiomics
from mlxradiomics import FEATURES
from mlxradiomics.config.settings import DEFAULT_FEATURES, FAMILIES

FAMILY_VARIANTS = {
    "firstorder": "FirstOrder",
    "glcm": "Glcm",
    "gldm": "Gldm",
    "ngtdm": "Ngtdm",
    "glrlm": "Glrlm",
    "glszm": "Glszm",
    "shape": "Shape",
    "shape2D": "Shape2D",
    "gldzm": "Gldzm",
    "intensityhistogram": "IntensityHistogram",
    "localintensity": "LocalIntensity",
    "ivh": "Ivh",
}


def source_label() -> str:
    """Name the mlx-radiomics source by git commit; editable installs report stale versions."""
    package = Path(mlxradiomics.__file__).resolve().parent
    try:
        commit = subprocess.run(
            ["git", "-C", str(package), "describe", "--always", "--dirty", "--abbrev=12"],
            check=True, capture_output=True, text=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return f"mlxradiomics {mlxradiomics.__version__}"
    return f"mlx-radiomics@{commit}"


def rust_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ibsi", type=Path, required=True)
    parser.add_argument("--rust", type=Path, required=True)
    parser.add_argument("--markdown", type=Path)
    args = parser.parse_args()

    if list(FAMILIES) != list(FAMILY_VARIANTS):
        raise SystemExit(f"family order changed: {list(FAMILIES)}")
    catalogue = [f"{family}_{name}" for family, names in FAMILIES.items() for name in names]
    if tuple(catalogue) != tuple(FEATURES):
        raise SystemExit("FAMILIES order does not reproduce FEATURES order")

    manifest = json.loads(args.ibsi.read_text())
    ibsi: dict[str, dict[str, str]] = {}
    for entry in manifest["definitions"]:
        for public in entry.get("public_names", ()):
            ibsi[public] = entry
    defaults = set(DEFAULT_FEATURES)

    rows = []
    for family, names in FAMILIES.items():
        for name in names:
            key = f"{family}_{name}"
            entry = ibsi.get(key, {})
            rows.append((family, name, key in defaults, entry.get("id"), entry.get("title"),
                         entry.get("units")))

    source = source_label()
    lines = [
        f"// @generated by validation/export_catalog.py from {source}. Do not edit.",
        "// IBSI identifiers and titles: IBSI reference manual, CC BY 4.0",
        "// (see THIRD_PARTY_NOTICES.md).",
        "",
        "use crate::config::settings::{Family, FeatureSpec};",
        "",
        f"pub(super) const FEATURES: [FeatureSpec; {len(rows)}] = [",
    ]
    def opt(value: str | None) -> str:
        return "None" if not value else f"Some({rust_str(value)})"

    for family, name, is_default, ibsi_id, title, units in rows:
        lines.append(
            f"    FeatureSpec {{ family: Family::{FAMILY_VARIANTS[family]}, name: {rust_str(name)}, "
            f"default: {str(is_default).lower()}, ibsi_id: {opt(ibsi_id)}, "
            f"ibsi_title: {opt(title)}, units: {opt(units)} }},"
        )
    lines += ["];", ""]
    args.rust.write_text("\n".join(lines))

    if args.markdown:
        md = [f"<!-- generated from {source} by validation/export_catalog.py -->", ""]
        for family, names in FAMILIES.items():
            md += [f"#### `{family}` ({len(names)})", "",
                   "| Feature | Default | IBSI ID | IBSI definition | Units | Status |",
                   "| --- | :---: | --- | --- | --- | --- |"]
            for row in rows:
                if row[0] != family:
                    continue
                _, name, is_default, ibsi_id, title, units = row
                md.append(f"| `{family}_{name}` | {'yes' if is_default else ''} | {ibsi_id or ''} "
                          f"| {title or ''} | {f'`{units}`' if units else ''} | todo |")
            md.append("")
        args.markdown.write_text("\n".join(md))

    print(f"{len(rows)} features, {len(defaults)} default, "
          f"{sum(1 for r in rows if r[3])} with IBSI identifiers")


if __name__ == "__main__":
    main()
